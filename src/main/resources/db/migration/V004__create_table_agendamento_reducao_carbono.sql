CREATE SEQUENCE SEQ_TB_AGENDAMENTO_REDUCAO
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE TB_AGENDAMENTO_REDUCAO_CARBONO (
    ID_AGENDAMENTO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_EMISSAO NUMBER NOT NULL,
    DS_ACAO VARCHAR2(255) NOT NULL,
    NM_RESPONSAVEL VARCHAR2(100) NOT NULL,
    DT_INICIO DATE NOT NULL,
    DT_PREVISAO DATE NOT NULL,
    QT_REDUCAO_ESTIMADA NUMBER(10,2) NOT NULL,
    ST_AGENDAMENTO VARCHAR2(20) NOT NULL,

    CONSTRAINT PK_TB_AGENDAMENTO_REDUCAO_CARBONO
        PRIMARY KEY (ID_AGENDAMENTO),

    CONSTRAINT FK_TB_AGENDAMENTO_EMISSAO
        FOREIGN KEY (ID_EMISSAO)
        REFERENCES TB_EMISSAO_CARBONO(ID_EMISSAO),

    CONSTRAINT CK_TB_AGENDAMENTO_STATUS
        CHECK (ST_AGENDAMENTO IN ('PENDENTE', 'CONCLUIDO', 'CANCELADO'))
);