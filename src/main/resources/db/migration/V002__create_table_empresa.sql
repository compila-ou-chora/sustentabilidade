CREATE SEQUENCE SEQ_TB_EMPRESA
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE TB_EMPRESA (
    ID_EMPRESA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NM_EMPRESA VARCHAR2(100) NOT NULL,
    NM_CIDADE VARCHAR2(100) NOT NULL,
    SG_ESTADO CHAR(2) NOT NULL,

    CONSTRAINT PK_TB_EMPRESA
        PRIMARY KEY (ID_EMPRESA)
);