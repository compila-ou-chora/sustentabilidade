CREATE SEQUENCE SEQ_TB_EMISSAO_CARBONO
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE TB_EMISSAO_CARBONO (
    ID_EMISSAO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_EMPRESA NUMBER NOT NULL,
    DS_FONTE_EMISSAO VARCHAR2(100) NOT NULL,
    DT_REGISTRO DATE NOT NULL,
    QT_CO2 NUMBER(10,2) NOT NULL,

    CONSTRAINT PK_TB_EMISSAO_CARBONO
        PRIMARY KEY (ID_EMISSAO),

    CONSTRAINT FK_TB_EMISSAO_EMPRESA
        FOREIGN KEY (ID_EMPRESA)
        REFERENCES TB_EMPRESA(ID_EMPRESA)
);